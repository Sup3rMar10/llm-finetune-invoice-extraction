"""Turn results/*.metrics.json and the training log into RESULTS.md + charts."""
import argparse
import glob
import json
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from src.common import FIELDS  # noqa: E402

ORDER = ["base-zeroshot", "base-fewshot", "tuned"]
COLORS = {"base-zeroshot": "#9aa5b1", "base-fewshot": "#6c8ebf", "tuned": "#2a9d8f"}
SPLITS = [("test_id", "In-distribution (seen layouts, new invoices)"),
          ("test_ood", "Out-of-distribution (layouts never seen in training)")]


def load(results_dir):
    runs = {}
    for path in glob.glob(os.path.join(results_dir, "*.metrics.json")):
        with open(path, encoding="utf-8") as f:
            m = json.load(f)
        runs[(m["name"], m["split"].replace(".jsonl", ""))] = m
    return runs


def write_tables(runs, names, results_dir):
    lines = ["# Results\n",
             "Generated by `python -m src.report`. Every number comes from `results/*.metrics.json`.\n"]
    for split, title in SPLITS:
        have = [n for n in names if (n, split) in runs]
        if not have:
            continue
        lines += [f"## {title}\n",
                  "| Model | Exact match | Field acc. (macro) | Valid JSON | Strict schema | s/sample |",
                  "|---|---|---|---|---|---|"]
        for n in have:
            m = runs[(n, split)]
            lines.append(f"| {n} | {m['exact_match']:.1%} | {m['field_accuracy_macro']:.1%} | "
                         f"{m['json_valid']:.1%} | {m['schema_valid']:.1%} | {m['seconds_per_sample']} |")
        lines.append(f"\n_n = {runs[(have[0], split)]['n']} invoices per row._\n")
        lines += ["Per-field accuracy:\n", "| Model | " + " | ".join(FIELDS) + " |",
                  "|---|" + "---|" * len(FIELDS)]
        for n in have:
            fa = runs[(n, split)]["field_accuracy"]
            lines.append(f"| {n} | " + " | ".join(f"{fa[f]:.0%}" for f in FIELDS) + " |")
        lines.append("")
    with open(os.path.join(results_dir, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def plot_comparison(runs, names, results_dir):
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.6), sharey=True)
    for ax, (split, title) in zip(axes, SPLITS, strict=True):
        have = [n for n in names if (n, split) in runs]
        vals = [runs[(n, split)]["exact_match"] * 100 for n in have]
        bars = ax.bar(have, vals, color=[COLORS[n] for n in have])
        ax.set_title(title.split(" (")[0], fontsize=10)
        ax.set_ylim(0, 105)
        for b, v in zip(bars, vals, strict=True):
            ax.text(b.get_x() + b.get_width() / 2, v + 1.5, f"{v:.0f}%", ha="center", fontsize=9)
        ax.tick_params(axis="x", labelsize=8)
    axes[0].set_ylabel("Exact-match accuracy (%)")
    fig.tight_layout()
    fig.savefig(os.path.join(results_dir, "comparison.png"), dpi=150)


def plot_loss(log_path, results_dir):
    with open(log_path, encoding="utf-8") as f:
        rows = [json.loads(line) for line in f]
    train = [(r["step"], r["loss"]) for r in rows if r["event"] == "train"]
    val = [(r["step"], r["val_loss"]) for r in rows if r["event"] == "eval"]
    fig, ax = plt.subplots(figsize=(6, 3.4))
    ax.plot(*zip(*train, strict=True), label="train loss")
    ax.plot(*zip(*val, strict=True), "o-", label="val loss")
    ax.set_xlabel("optimizer step")
    ax.set_ylabel("loss (answer tokens only)")
    ax.set_yscale("log")
    ax.legend()
    fig.tight_layout()
    fig.savefig(os.path.join(results_dir, "loss_curve.png"), dpi=150)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--log", default="results/train_log.jsonl")
    a = ap.parse_args()
    runs = load(a.results)
    names = [n for n in ORDER if any(k[0] == n for k in runs)]
    write_tables(runs, names, a.results)
    plot_comparison(runs, names, a.results)
    if os.path.exists(a.log):
        plot_loss(a.log, a.results)
    print("wrote RESULTS.md, comparison.png, loss_curve.png")


if __name__ == "__main__":
    main()
